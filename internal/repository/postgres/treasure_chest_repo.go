// GetBySource retrieves all treasure chests with a specific source
func (r *treasureChestRepository) GetBySource(
	ctx context.Context,
	source string,
) ([]*models.TreasureChest, error) {
	query := `
		SELECT id, source, qr_match, is_secure, status, first_score, subsequent_score, created_by, created_at, updated_at
		FROM treasure_chest
		WHERE source = $1
		ORDER BY created_at ASC
	`

	rows, err := r.db.QueryContext(ctx, query, source)
	if err != nil {
		return nil, fmt.Errorf("failed to get chests by source: %w", err)
	}
	defer rows.Close()

	var chests []*models.TreasureChest
	for rows.Next() {
		chest := &models.TreasureChest{}
		err := rows.Scan(
			&chest.ID,
			&chest.Source,
			&chest.QRMatch,
			&chest.IsSecure,
			&chest.Status,
			&chest.FirstScore,
			&chest.SubsequentScore,
			&chest.CreatedBy,
			&chest.CreatedAt,
			&chest.UpdatedAt,
		)
		if err != nil {
			return nil, fmt.Errorf("failed to scan chest: %w", err)
		}
		chests = append(chests, chest)
	}

	if err := rows.Err(); err != nil {
		return nil, fmt.Errorf("error iterating rows: %w", err)
	}

	return chests, nil
}

// CheckSourceExists checks if a source already exists
func (r *treasureChestRepository) CheckSourceExists(
	ctx context.Context,
	source string,
) (bool, error) {
	query := `SELECT EXISTS(SELECT 1 FROM treasure_chest WHERE source = $1)`

	var exists bool
	err := r.db.QueryRowContext(ctx, query, source).Scan(&exists)
	if err != nil {
		return false, fmt.Errorf("failed to check if source exists: %w", err)
	}

	return exists, nil
}

// Update updates an existing treasure chest
func (r *treasureChestRepository) Update(ctx context.Context, chest *models.TreasureChest) error {
	query := `
		UPDATE treasure_chest
		SET status = $1, updated_at = CURRENT_TIMESTAMP
		WHERE id = $2
		RETURNING updated_at
	`

	err := r.db.QueryRowContext(ctx, query, chest.Status, chest.ID).Scan(&chest.UpdatedAt)
	if err == sql.ErrNoRows {
		return fmt.Errorf("chest with ID '%s' not found", chest.ID)
	}
	if err != nil {
		return fmt.Errorf("failed to update chest: %w", err)
	}

	return nil
}

